/**
 * Items the energy check skips, with the reason.
 * Beer carries alcohol, which supplies about 7 kcal per gram and is not part of
 * the 4C + 4P + 9F estimate, so the check would always flag it.
 */
const ENERGY_CHECK_SKIP = new Set<string>(["beer"]);

/**
 * Rough energy check: calories should be near 4C + 4P + 9F. Returns the ids that fail.
 *
 * Differences of 10 kcal or less per 100 g are ignored, because on very low
 * calorie foods (leafy greens, broth, black coffee) a few kcal of rounding is a
 * large percentage and says nothing about whether the entry is right.
 */
export function energyOutliers(tolerance = 0.2): string[] {
  const failing: string[] = [];
  for (const food of SEED_FOODS) {
    if (ENERGY_CHECK_SKIP.has(food.id)) continue;
    const estimate = 4 * food.carbsG + 4 * food.proteinG + 9 * food.fatG;
    const difference = Math.abs(food.caloriesKcal - estimate);
    if (difference <= 10) continue;
    if (estimate <= 0 || difference / estimate > tolerance) failing.push(food.id);
  }
  return failing;
}
